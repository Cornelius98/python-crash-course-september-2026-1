#Integer
my_integer = 10
print("Integer: ", my_integer)

#Float
my_float = 299.99
print("Float (Decimal Number): ", my_float)

#Character
my_character = "A"
print("Character: ", my_character)

#String
my_string = "Hello World"
print("String: ", my_string)

#Booleans
is_true = True
print("Boolean True: ", is_true)

is_false = False
print("Boolean False: ", is_false)

#List
list_fruits = ["apple", "banana", "cherry", "guava"]
print("List: ", list_fruits)

#Tuple
my_tuple = (1, 2, 3, 4)
print("Tuple: ", my_tuple)

#Set
my_set = {"apple", "banana", "cherry", "guava"}
print("Set: ", my_set)

#Dictionary
my_dictionary = {"name":"Guido Van Rossum", "founder":"Python", "age":"89"}
print("Dictionary: ", my_dictionary)

#Bytes
my_bytes = b"Hello World"
print("Bytes: ", my_bytes)

#Byte Array
my_byte_array = bytearray(my_bytes)
print("Byte Array: ", my_byte_array)
print("Byte Array 0", my_byte_array[0])
print("Byte Array 1", my_byte_array[1])

#Memoryview
my_memoryview = memoryview(my_byte_array)
print("Memory View: ", my_memoryview)

#None
my_none = None
print("None: ", my_none)
