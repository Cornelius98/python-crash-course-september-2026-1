#Addition (+)
sum_1 = 10
sum_2 = 20
sum = sum_1 + sum_2 + 10
print("Sum: ", sum)

#Subtraction (-)
sub_1 = 200
sub_2 = 100
difference = sub_1 - sub_2
print("Difference: ", difference)

#Multiplication (*)
multi_1 = 10
multi_2 = 0
product = multi_1 * multi_2
print("Product: ", product)

#Division
numerator = 5
denominator = 2
quotient = numerator / denominator #Ceiling
print("Quotient: ", quotient)

quotient_2 = numerator // denominator #Floor division
print("Quotient Two: ", quotient_2)

#Modulus (%)
remainder = numerator % denominator
print("Remainder: ", remainder)

#Exponents and indices (2 power 3)
base = 2
exponent = 3
result = pow(base, exponent)
print("Exponent Result: ", result)

result_2 = base ** exponent
print("Result 2: ", result_2)

