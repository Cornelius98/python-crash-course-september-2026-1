#Variables to use
a = 30
b = 30

#Greater than operator (>)
if a > b:
    print("a is greater than b")
else:
    print("a is not greater than b")

#Greater than or equal to operator (>=)
if a >= b:
    print("a is greater than or equal to b")
else:
    print("a is not greater than or equal to b")
    print("a is not greater than or equal to b")

l1 = 100
l2 = 100

#Less than operator (<)
if l1 < l2:
    print("l1 is less than l2")
else:
    print("l1 is not less than l2")

#Less than or equal to operator (<=)
if l1 <= l2:
    print("l1 is less than or equal to l2")
else:
    print("l1 is not less than or equal to l2")

#Not equal to operator (!= || <>(Not supported))
ne_1 = 200
ne_2 = 100
if ne_1 != ne_2:
    print("ne_1 is not equal to ne_2")
else:
    print("ne_1 is equal to ne_2")

#Equality by value operator
eq_1 = 200
eq_2 = 500
if eq_1 == eq_2:
    print("eq_1 is equal to eq_2")
else:
    print("eq_1 is not equal to eq_2")