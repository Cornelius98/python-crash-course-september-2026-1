#or operator - requires one condition to be true, for true output
a = 10
b = 20
c = 30

if c>b or a>b:
    print("True is greater")
else:
    print("False is less than")

#and operator - requires all conditions to be true,to give true output
j = 10
k = 20
q = 30

if k>j and q>j:
    print("True is greater for and operator")
else:
    print("False is less than for and operator")