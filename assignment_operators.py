#Plus equal to operator (+=)
a = 100
a = a + 20
print("Long hand notation: ", a) #Long hand notation

a+=30
print("Short hand notation: ", a)

#Minus equal to operator(-=)
b = 100
b = b - 50
print("Long hand notation -=: ", b)

b-=25
print("Short hand notation -=: ", b)

#Multiplication equal to operator (*=)
c = 10
c = c * 10
print("Long hand notation *=: ", c)

c*=10
print("Short hand notation *=: ", c)

#Divide equal to operator (/=)
d = 100
d = d / 2
print("Long hand notation /=: ", d)

d /=2
print("Short hand notation /=: ", d)

#Modulus equal to (%=)
e = 100
e = e % 2
print("Long hand notation %=: ", e)

e2 = 100
e2 %= 2
print("Short hand notation %=: ", e2)